# Full-detail refresh: every park at Geofabrik level, one country per run.
#
# `--enrich-missing` only ever fired for a park with ZERO rows, so the 159
# parks carrying the old HeiGIT import (major roads only: primary/secondary/
# trunk, no track/path/residential) were permanently "not missing" and stayed
# at that detail. Only 5 parks had a single track or path, while an AOI
# ingested from the same PBFs has 6,458 paths and 3,642 tracks -- the visible
# mismatch between a park outline and the AOI drawn over it.
#
# A country PBF is ~50-750 MB and is the whole cost, so the unit of work is a
# COUNTRY, not a park: download once, extract every park of that country, then
# delete. 33 countries, one per nightly run, so the corpus turns over monthly.
# State lives in a small json rather than a table -- it is scheduling
# bookkeeping, not data, and it must survive a db restore.

STATE_PATH = "data/osm_enrich_state.json"


def _utcnow():
    from datetime import datetime, timezone
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def _load_state():
    try:
        return json.load(open(STATE_PATH))
    except Exception:
        return {}


def _save_state(state):
    os.makedirs(os.path.dirname(STATE_PATH), exist_ok=True)
    tmp = STATE_PATH + ".tmp"
    with open(tmp, "w") as fh:
        json.dump(state, fh, indent=1, sort_keys=True)
    os.replace(tmp, STATE_PATH)


def _parks_by_country(iso=None):
    parks = [p for p in json.load(open("data/keystones_with_boundaries.json"))
             if p.get("geometry")]
    by_iso = {}
    for p in parks:
        c = p["id"].split("_")[0]
        if c not in GEOFABRIK:
            continue
        if iso and c != iso:
            continue
        by_iso.setdefault(c, []).append(p)
    return by_iso


def enrich_country(country, parks, buffer_km=50, dry_run=False):
    """Re-extract every park of one country at full Geofabrik detail.

    force=True on purpose: this is a refresh, not a backfill. The delete is
    scoped to (park_id) inside enrich_park_infra and each park is committed
    before the next, so an interrupted run leaves earlier parks correct and
    the state file simply does not advance."""
    if dry_run:
        print(f"{country}: would refresh {len(parks)} parks")
        return 0
    import shutil
    import tempfile
    import time
    t0 = time.time()
    pbf, temporary = ensure_pbf(country, max_age_days=PBF_CACHE_MAX_AGE_DAYS)
    work = tempfile.mkdtemp(prefix=f"osm_enrich_{country}_", dir="/tmp")
    done = 0
    try:
        # Two passes over the country instead of one per park (see
        # ROTATION_FILTER). The country file is deleted as soon as the
        # filtered copy exists, so the peak on disk is one country, not
        # a country plus every park of it.
        src = pbf
        try:
            src = prefilter(pbf, os.path.join(work, "infra.osm.pbf"))
            if temporary:
                os.remove(pbf)
        except (subprocess.CalledProcessError, OSError) as ex:
            print(f"  prefilter failed, extracting from the full file: {ex}",
                  file=sys.stderr)
        bboxes = {p["id"]: park_bbox(p, buffer_km) for p in parks}
        areas, nodes = {}, None
        try:
            ways, nodes = prepare_rotation(src, work)
            areas = extract_many(ways, bboxes, work)
            os.remove(ways)
        except (subprocess.CalledProcessError, OSError) as ex:
            print(f"  multi-extract failed, falling back to one pass per "
                  f"park: {ex}", file=sys.stderr)
            areas, nodes = {}, None
        print(f"  {country}: extracts ready in {time.time() - t0:.0f}s",
              file=sys.stderr)
        for p in parks:
            print(f"  {p['id']}", file=sys.stderr)
            area = areas.get(p["id"])
            park_nodes = None
            if area and os.path.exists(area):
                # A multi-extract area is node-renumbered: it is only usable
                # together with this park's original-id nodes.
                try:
                    park_nodes = extract_nodes(
                        nodes, bboxes[p["id"]],
                        os.path.join(work, "park_nodes.osm.pbf"))
                except (subprocess.CalledProcessError, OSError) as ex:
                    print(f"  node extract failed {p['id']}: {ex}",
                          file=sys.stderr)
                    area = None
            if not area or not os.path.exists(area):
                try:
                    area = extract_bbox(src, p["id"], bboxes[p["id"]])
                except subprocess.CalledProcessError as ex:
                    print(f"  extract failed {p['id']}: {ex}", file=sys.stderr)
                    continue
            try:
                enrich_park_infra(area, p["id"], force=True,
                                  nodes_pbf=park_nodes)
                _osm_hydro_fallback(area, p["id"])
                done += 1
            finally:
                try: os.remove(area)
                except OSError: pass
    finally:
        shutil.rmtree(work, ignore_errors=True)
        if temporary:
            try: os.remove(pbf)
            except OSError: pass
    print(f"  {country}: {done}/{len(parks)} parks in {time.time() - t0:.0f}s",
          file=sys.stderr)
    return done


def _osm_hydro_fallback(area_pbf, park_id):
    """Rivers and lakes from OSM for a park that has no HydroSHEDS import.

    data.hydrosheds.org has been behind a Cloudflare challenge since
    2026-08-07, so a park onboarded after that (DZA_Djurdjura,
    GNQ_Reserva_de_la_Paz) had roads and villages and not one river. The
    parks' consumers already read OSM rows (negative ids, scripts/osm_hydro.py
    -- it is what every AOI has). A park WITH HydroRIVERS reaches keeps them
    and only gets names; mixing both would draw every river twice."""
    import sqlite3
    import osm_hydro
    db = sqlite3.connect(DB_PATH, timeout=30)
    try:
        for table, col, fn in (("park_rivers_hydro", "hyriv_id", osm_hydro.rivers_from_pbf),
                               ("park_lakes_hydro", "hylak_id", osm_hydro.lakes_from_pbf)):
            imported = db.execute(
                f"SELECT 1 FROM {table} WHERE park_id = ? AND {col} > 0 LIMIT 1",
                (park_id,)).fetchone()
            if imported:
                continue
            fn(db, park_id, area_pbf, replace=True, keep_on_empty=True,
               log=lambda m: print(m, file=sys.stderr))
    finally:
        db.close()


def _infra_counts(parks):
    """(places, roads) row totals for a list of parks."""
    import sqlite3
    ids = [p["id"] for p in parks]
    q = ",".join("?" * len(ids))
    db = sqlite3.connect(f"file:{DB_PATH}?mode=ro", uri=True)
    try:
        pl = db.execute(f"SELECT COUNT(*) FROM osm_places WHERE park_id IN ({q})",
                        ids).fetchone()[0]
        rd = db.execute(f"SELECT COUNT(*) FROM roads_heigit WHERE park_id IN ({q})",
                        ids).fetchone()[0]
        return pl, rd
    finally:
        db.close()


def enrich_all(iso=None, buffer_km=50, dry_run=False, rotate=0):
    """Refresh every park to full Geofabrik detail.

    rotate=N: only the N least-recently-refreshed countries this run (the
    nightly mode). rotate=0: all of them, which is the ~hours-long one-off.

    Every country reports into the notification panel, success or failure --
    a nightly job nobody can see is a nightly job nobody notices stopping.
    """
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    from cron_notify import notify_status

    by_iso = _parks_by_country(iso)
    if not by_iso:
        print("no parks match")
        return
    if not dry_run:
        # Two rotations at once (a manual run meeting the 05:15 cron) would
        # each hold ~2 GB of osmium and interleave deletes on the same parks.
        import fcntl
        global _ROTATION_LOCK
        _ROTATION_LOCK = open(STATE_PATH + ".lock", "w")
        try:
            fcntl.flock(_ROTATION_LOCK, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except OSError:
            print("another OSM rotation is running; not starting a second",
                  file=sys.stderr)
            return
    state = _load_state()
    order = sorted(by_iso, key=lambda c: (state.get(c, {}).get("at", ""), c))
    if rotate:
        order = order[:rotate]
    for country in order:
        parks = by_iso[country]
        print(f"== {country}: {len(parks)} parks", file=sys.stderr)
        if dry_run:
            enrich_country(country, parks, buffer_km, dry_run)
            continue
        before = _infra_counts(parks)
        try:
            n = enrich_country(country, parks, buffer_km, dry_run)
        except Exception as ex:  # noqa: BLE001
            # One country's PBF being unavailable must not cost the other
            # country in tonight's rotation its turn.
            print(f"{country} failed: {ex}", file=sys.stderr)
            notify_status("osm_enrich_failed", "OSM Detail Refresh Failed",
                          f"{country}: {str(ex)[:200]}")
            continue
        # A country that enriched no park did not succeed -- leave its state
        # entry untouched so the rotation retries it tomorrow rather than
        # freezing a wrong answer as fresh (AGENTS.md: the no-op that reads
        # as an answer).
        if n == 0:
            notify_status("osm_enrich_failed", "OSM Detail Refresh Failed",
                          f"{country}: 0 of {len(parks)} parks enriched "
                          f"(PBF or extract failed); will retry next run")
            continue
        after = _infra_counts(parks)
        state[country] = {"at": _utcnow(), "parks": n,
                          "places": after[0], "roads": after[1]}
        _save_state(state)
        # Counted over ALL countries, not the --iso subset: the point of the
        # number is "how much of the corpus is still on the thin HeiGIT
        # import", which a filtered run must not misreport as nearly done.
        all_countries = _parks_by_country()
        never = len([c for c in all_countries if c not in state])
        notify_status(
            "osm_enrich_success", "OSM Detail Refresh Complete",
            f"{country}: {n}/{len(parks)} parks refreshed from Geofabrik - "
            f"{after[1]:,} roads ({after[1] - before[1]:+,}), "
            f"{after[0]:,} places ({after[0] - before[0]:+,}); "
            f"{never}/{len(all_countries)} countries still never refreshed")


