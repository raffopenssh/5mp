#!/usr/bin/env python3
"""Train the plane-vs-helicopter model and write srv/gpx/aircraft_subtype_model.go.

    go run ./cmd/movement-eval -dump-aircraft /tmp/air.csv
    python3 scripts/train_aircraft_subtype.py /tmp/air.csv

The table is produced by the harness from the SAME Go feature code production
runs (gpx.AircraftFeatures), so training and serving cannot drift. Only the
`history` corpus is trained on: `raw` and `labelled` stay out-of-sample, which
is what makes the harness's subtype numbers for them a test and not a recital.

The model is a standardised logistic regression on features expressed in units
of the journey's own cruise speed. Absolute speed is deliberately not a
feature: in this fleet the helicopter happens to cruise faster than the plane,
which is a fact about two airframes, not about rotors.

Thresholds (the abstain band) are chosen on grouped cross-validation inside
the training corpus for a target precision, never on the test corpora.
"""
import sys
import numpy as np
import pandas as pd
from sklearn.linear_model import LogisticRegression
from sklearn.model_selection import GroupKFold
from sklearn.metrics import roc_auc_score

TARGET_PRECISION = 0.90
C = 0.3
OUT = "srv/gpx/aircraft_subtype_model.go"

d = pd.read_csv(sys.argv[1])
feats = list(d.columns[7:])
d["y"] = (d["sub"] == "rotor_wing").astype(int)
tr = d[d.source == "history"].reset_index(drop=True)
te = d[(d.source != "history") & d.strong].reset_index(drop=True)


def prep(X, st=None):
    X = X.to_numpy(float)
    if st is None:
        med = np.nanmedian(X, axis=0)
        lo, hi = np.nanpercentile(X, 1, axis=0), np.nanpercentile(X, 99, axis=0)
        Xc = np.clip(np.where(np.isnan(X), med, X), lo, hi)
        mean, sd = Xc.mean(0), Xc.std(0)
        sd[sd < 1e-9] = 1.0
        st = (med, lo, hi, mean, sd)
    med, lo, hi, mean, sd = st
    Xc = np.clip(np.where(np.isnan(X), med, X), lo, hi)
    return (Xc - mean) / sd, st


def fit(df):
    X, st = prep(df[feats])
    m = LogisticRegression(C=C, class_weight="balanced", max_iter=5000).fit(X, df.y)
    return m, st


def predict(m, st, df):
    return m.predict_proba(prep(df[feats], st)[0])[:, 1]


# Grouped CV inside training: a journey's file never appears on both sides.
oof = np.zeros(len(tr))
for a, b in GroupKFold(5).split(tr, tr.y, tr.file):
    m, st = fit(tr.iloc[a])
    oof[b] = predict(m, st, tr.iloc[b])
print("train (history) %d journeys, %d rotor; grouped-CV AUC %.3f" % (len(tr), tr.y.sum(), roc_auc_score(tr.y, oof)))


def threshold(score, y):
    """Lowest threshold at which precision for y==1 is still >= target.

    Precision is computed with the two classes weighted equally: helicopters are
    10% of this corpus's journeys, and a threshold tuned to that mix would be
    wrong for any fleet with a different one.
    """
    pos, neg = max(1, (y == 1).sum()), max(1, (y == 0).sum())
    best = 1.01
    for t in np.unique(np.round(score, 2))[::-1]:
        if t < 0.5:
            break
        sel = score >= t
        tp, fp = (sel & (y == 1)).sum() / pos, (sel & (y == 0)).sum() / neg
        if tp + fp > 0 and tp / (tp + fp) >= TARGET_PRECISION:
            best = t
    return float(best)


rotor_above = threshold(oof, tr.y.to_numpy())
fixed_below = 1 - threshold(1 - oof, 1 - tr.y.to_numpy())
print("abstain band: fixed_wing <= %.3f < (no answer) < %.3f <= rotor_wing" % (fixed_below, rotor_above))

m, st = fit(tr)
med, lo, hi, mean, sd = st


def report(name, df, p):
    y, km = df.y.to_numpy(), df.km.to_numpy()
    r, f = p >= rotor_above, p <= fixed_below
    auc = roc_auc_score(y, p) if 0 < y.sum() < len(y) else float("nan")
    print("%-18s n=%3d AUC %.3f | rotor P %.2f R %.2f | fixed P %.2f R %.2f | abstain %.0f%% of journeys, %.0f%% of km" % (
        name, len(df), auc,
        (r & (y == 1)).sum() / max(1, r.sum()), (r & (y == 1)).sum() / max(1, (y == 1).sum()),
        (f & (y == 0)).sum() / max(1, f.sum()), (f & (y == 0)).sum() / max(1, (y == 0).sum()),
        100 * (~r & ~f).mean(), 100 * km[~r & ~f].sum() / km.sum()))


report("history (CV)", tr, oof)
for src in sorted(te.source.unique()):
    report(src + " (held out)", te[te.source == src], predict(m, st, te[te.source == src]))

order = np.argsort(-np.abs(m.coef_[0]))[:8]
print("strongest features:", ", ".join("%s %+.2f" % (feats[i], m.coef_[0][i]) for i in order))


def arr(v):
    return "[]float64{" + ", ".join("%.6g" % x for x in v) + "}"


with open(OUT, "w") as fh:
    fh.write("// Code generated by scripts/train_aircraft_subtype.py; DO NOT EDIT.\n")
    fh.write("//\n// Trained on %d journeys of the `history` eval corpus (%d rotor_wing).\n" % (len(tr), tr.y.sum()))
    fh.write("// Grouped-CV AUC %.3f. Re-measure with: go run ./cmd/movement-eval\n\n" % roc_auc_score(tr.y, oof))
    fh.write("package gpx\n\n")
    fh.write("// aircraftSubtypeFeatures is the feature order the table was trained with;\n")
    fh.write("// TestAircraftModelMatchesFeatures fails if AircraftFeatureNames drifts from it.\n")
    fh.write("var aircraftSubtypeFeatures = []string{" + ", ".join('"%s"' % f for f in feats) + "}\n\n")
    fh.write("var aircraftSubtypeModel = aircraftSubtypeModelT{\n")
    fh.write("\tIntercept:  %.6g,\n" % m.intercept_[0])
    fh.write("\tCoef:       %s,\n" % arr(m.coef_[0]))
    fh.write("\tMean:       %s,\n" % arr(mean))
    fh.write("\tScale:      %s,\n" % arr(sd))
    fh.write("\tMedian:     %s,\n" % arr(med))
    fh.write("\tClip:       [][2]float64{" + ", ".join("{%.6g, %.6g}" % (a, b) for a, b in zip(lo, hi)) + "},\n")
    fh.write("\tRotorAbove: %.3f,\n\tFixedBelow: %.3f,\n}\n" % (rotor_above, fixed_below))
print("wrote", OUT)
