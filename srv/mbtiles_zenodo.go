// HandleAPIZenodoMBTilesCreate starts a new MBTiles-to-Zenodo job.
func (s *Server) HandleAPIZenodoMBTilesCreate(w http.ResponseWriter, r *http.Request) {
	if zenodoMBQueue == nil {
		http.Error(w, "Zenodo MBTiles not configured", http.StatusServiceUnavailable)
		return
	}

	parkID := r.PathValue("id")
	if parkID == "" {
		http.Error(w, "Park ID required", http.StatusBadRequest)
		return
	}

	area := s.AreaStore.GetByID(parkID)
	if area == nil {
		http.Error(w, "Park not found", http.StatusNotFound)
		return
	}

	source := r.URL.Query().Get("source")
	if source == "" {
		source = "esri"
	}
	if _, ok := TileSources[source]; !ok {
		http.Error(w, "Invalid source. Use: esri, bing, google", http.StatusBadRequest)
		return
	}

	maxZoom := 17
	if mzStr := r.URL.Query().Get("maxZoom"); mzStr != "" {
		if mz, err := fmt.Sscanf(mzStr, "%d", &maxZoom); err != nil || mz < 1 {
			maxZoom = 17
		}
		if maxZoom < 1 {
			maxZoom = 1
		}
		if maxZoom > 19 {
			maxZoom = 19
		}
	}

	bufferKm := 5.0
	bbox := calculateBufferedBBox(area, bufferKm)
	tiles := calculateTiles(bbox, 1, maxZoom)
	estimatedSize := estimateTileBytes(len(tiles))
	ramNeeded := estimateRAMRequired(bbox, 1, maxZoom)

	// Check RAM limit (leave 2GB headroom for OS + server)
	const maxRAM = 6 * 1024 * 1024 * 1024 // 6GB peak RAM (leaves ~1GB for OS+server)
	if ramNeeded > maxRAM {
		http.Error(w, fmt.Sprintf(
			"Estimated size too large for in-memory build: ~%.1f GB (max ~%.1f GB). Reduce zoom level.",
			float64(estimatedSize)/(1024*1024*1024),
			float64(maxRAM)/2.1/(1024*1024*1024),
		), http.StatusRequestEntityTooLarge)
		return
	}

	job := &ZenodoMBTilesJob{
		ID:       fmt.Sprintf("%d", time.Now().UnixNano()),
		ParkID:   parkID,
		ParkName: area.Name,
		Source:   source,
		MinZoom:  1,
		MaxZoom:  maxZoom,
		BufferKm: bufferKm,
		BBox:     bbox,
	}

	zenodoMBQueue.addJob(job)

	estSeconds := len(tiles) / 100
	if estSeconds < 60 {
		estSeconds = 60
	}

	w.Header().Set("Content-Type", "application/json")
	json.NewEncoder(w).Encode(map[string]interface{}{
		"job_id":            job.ID,
		"park_id":           parkID,
		"source":            source,
		"total_tiles":       len(tiles),
		"estimated_size_mb": estimatedSize / (1024 * 1024),
		"estimated_seconds": estSeconds,
		"storage":           "zenodo",
		"status_url":        fmt.Sprintf("/api/mbtiles/%s/status?pwd=%s", job.ID, r.URL.Query().Get("pwd")),
	})
}

// HandleAPIZenodoMBTilesEstimate returns size/time estimates for Zenodo upload.
func (s *Server) HandleAPIZenodoMBTilesEstimate(w http.ResponseWriter, r *http.Request) {
	parkID := r.PathValue("id")
	area := s.AreaStore.GetByID(parkID)
	if area == nil {
		http.Error(w, "Park not found", http.StatusNotFound)
		return
	}

	maxZoom := 17
	if mzStr := r.URL.Query().Get("maxZoom"); mzStr != "" {
		fmt.Sscanf(mzStr, "%d", &maxZoom)
		if maxZoom < 1 {
			maxZoom = 1
		}
		if maxZoom > 19 {
			maxZoom = 19
		}
	}

	bbox := calculateBufferedBBox(area, 5.0)
	tiles := calculateTiles(bbox, 1, maxZoom)
	estimatedSize := estimateTileBytes(len(tiles))
	ramNeeded := estimateRAMRequired(bbox, 1, maxZoom)
	estSeconds := len(tiles) / 100

	const maxRAM = 6 * 1024 * 1024 * 1024
	sufficient := ramNeeded <= maxRAM

	// Check if already uploaded to Zenodo
	key := fmt.Sprintf("mbtiles_%s_%s", parkID, r.URL.Query().Get("source"))
	if key == fmt.Sprintf("mbtiles_%s_", parkID) {
		key = fmt.Sprintf("mbtiles_%s_esri", parkID)
	}
	var existingDepoID int
	if zenodoMBQueue != nil {
		if entry := zenodoMBQueue.zenodoManifest.Get(key); entry != nil {
			existingDepoID = entry.DepoID
		}
	}

	w.Header().Set("Content-Type", "application/json")
	json.NewEncoder(w).Encode(map[string]interface{}{
		"park_id":           parkID,
		"total_tiles":       len(tiles),
		"estimated_size_mb": estimatedSize / (1024 * 1024),
		"estimated_seconds": estSeconds,
		"bbox":              bbox,
		"min_zoom":          1,
		"max_zoom":          maxZoom,
		"sufficient_space":  sufficient,
		"storage":           "zenodo",
		"ram_needed_mb":     ramNeeded / (1024 * 1024),
		"existing_depo_id":  existingDepoID,
		"sources":           []string{"esri", "bing", "google"},
	})
}

// HandleAPIZenodoMBTilesStatus returns job status (reuses the same endpoint path).
func (s *Server) HandleAPIZenodoMBTilesStatus(w http.ResponseWriter, r *http.Request) {
	jobID := r.PathValue("id")

	// Check Zenodo queue first
	if zenodoMBQueue != nil {
		if job := zenodoMBQueue.getJob(jobID); job != nil {
			w.Header().Set("Content-Type", "application/json")
			json.NewEncoder(w).Encode(job)
			return
		}
	}

	// Fall back to legacy disk-based queue
	if mbtilesQueue != nil {
		if job := mbtilesQueue.GetJob(jobID); job != nil {
			w.Header().Set("Content-Type", "application/json")
			json.NewEncoder(w).Encode(job)
			return
		}
	}

	http.Error(w, "Job not found", http.StatusNotFound)
}

// HandleAPIZenodoMBTilesDownload proxies the download from Zenodo (or redirects).
func (s *Server) HandleAPIZenodoMBTilesDownload(w http.ResponseWriter, r *http.Request) {
	jobID := r.PathValue("id")

	// Check active Zenodo job first
	if zenodoMBQueue != nil {
		if job := zenodoMBQueue.getJob(jobID); job != nil {
			if job.Status != "completed" {
				http.Error(w, fmt.Sprintf("Job not ready: %s", job.Status), http.StatusBadRequest)
				return
			}
			if job.DownloadURL != "" {
				proxyZenodoDownload(w, job.DownloadURL, fmt.Sprintf("%s_%s.mbtiles", job.ParkID, job.Source))
				return
			}
			http.Error(w, "No download URL available", http.StatusNotFound)
			return
		}

		// Job expired but may still be in manifest — look up by key param
		if key := r.URL.Query().Get("key"); key != "" {
			if entry := zenodoMBQueue.zenodoManifest.Get(key); entry != nil {
				downloadURL := fmt.Sprintf("%s/%s", entry.BucketURL, entry.Filename)
				proxyZenodoDownload(w, downloadURL, entry.Filename)
				return
			}
		}
	}

	// Fall back to legacy disk-based download
	s.HandleAPIMBTilesDownload(w, r)
}

// proxyZenodoDownload streams a file from Zenodo to the client.
func proxyZenodoDownload(w http.ResponseWriter, downloadURL, filename string) {
	q := zenodoMBQueue
	req, err := http.NewRequest("GET", downloadURL, nil)
	if err != nil {
		http.Error(w, "Failed to create request", http.StatusInternalServerError)
		return
	}
	req.Header.Set("Authorization", "Bearer "+q.zenodoClient.Token)

	resp, err := q.zenodoClient.HTTPClient.Do(req)
	if err != nil {
		http.Error(w, "Failed to fetch from Zenodo", http.StatusBadGateway)
		return
	}
	defer resp.Body.Close()

	w.Header().Set("Content-Disposition", fmt.Sprintf("attachment; filename=%s", filename))
	w.Header().Set("Content-Type", "application/x-sqlite3")
	if resp.ContentLength > 0 {
		w.Header().Set("Content-Length", fmt.Sprintf("%d", resp.ContentLength))
	}
	w.WriteHeader(resp.StatusCode)
	buf := make([]byte, 256*1024)
	for {
		n, readErr := resp.Body.Read(buf)
		if n > 0 {
			w.Write(buf[:n])
		}
		if readErr != nil {
			break
		}
	}
}

// HandleAPIZenodoMBTilesList lists jobs from both queues.
func (s *Server) HandleAPIZenodoMBTilesList(w http.ResponseWriter, r *http.Request) {
	var allJobs []interface{}

	if zenodoMBQueue != nil {
		for _, j := range zenodoMBQueue.listJobs() {
			allJobs = append(allJobs, j)
		}
	}

	// Include legacy jobs too
	if mbtilesQueue != nil {
		for _, j := range mbtilesQueue.ListJobs() {
			allJobs = append(allJobs, j)
		}
	}

	w.Header().Set("Content-Type", "application/json")
	json.NewEncoder(w).Encode(allJobs)
}

